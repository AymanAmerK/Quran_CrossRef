// Helper function to get surah by number
export function getSurahByNumber(number) {
  return SURAH_NAMES.find(s => s.number === number);
}

// Helper function to get surah name
export function getSurahName(number, language = 'en') {
  const surah = getSurahByNumber(number);
  if (!surah) return '';
  return language === 'ar' ? surah.nameArabic : surah.nameEnglish;
}
